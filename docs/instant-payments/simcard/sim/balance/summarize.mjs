// Regenerates the simulation tables of docs/chip-balance-design.md (between the BALANCE-SIM markers) from
// sim/balance/results/balance-results.json. Run balance-sim.mjs first.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const R = JSON.parse(readFileSync(join(HERE, 'results', 'balance-results.json'), 'utf8'));
const DOC = join(HERE, '..', '..', 'docs', 'chip-balance-design.md');
const f = (x) => (x === null || x === undefined ? 'n/a' : Math.round(x).toLocaleString('en-US'));
const pct = (x) => (x > 100 ? 'over 100% (vault emptied)' : x.toFixed(1) + '%');
const resp = (s) => (s.response === 'revoke' ? 'revocation only' : s.response === 'fresh' ? `freshness, ${s.delta} days` : 'emergency freeze');
const P = R.parameters, H = R.honest;
const L = [];
L.push('<!-- BALANCE-SIM:BEGIN (generated by sim/balance/summarize.mjs) -->');
L.push('### 8.1 Model and honest economy (ASSUMED model)');
L.push('');
L.push(`${f(P.consumers)} consumers and ${f(P.merchants)} merchants on ${P.vendors} vendors, ${P.days} days, daily flows. Consumers spend ${P.spendPerConsumerDay} USDw a day by chip; merchants pay ${P.wageShare * 100}% back as wages and ${P.supplierShare * 100}% to suppliers chip to chip, and turn the rest into savings, half by selling to consumers through swaps and half by defunding. Holding cap ${f(P.cap)}; chip defund window ${f(P.chipWeeklyDefund)} a week; vault brake ${P.brakePctPerDay}% a day; vendor bond ${f(P.vendorBond)} each with a weekly allowance of ${P.vendorAllowancePctPerWeek}% of the bond; 0.1% defund fee kept in the vault.`);
L.push('');
L.push('| Measure | Value |');
L.push('|---|---|');
L.push(`| Chip payments per day | ${f(H.perDay.spend)} USDw |`);
L.push(`| Funding (FUND) / swaps / defunds per day | ${f(H.perDay.funds)} / ${f(H.perDay.swaps)} / ${f(H.perDay.defunds)} USDw |`);
L.push(`| Vault reserve (= all checking balances) | ${f(H.reserve)} USDw |`);
L.push(`| Vault brake capacity per day | ${f(H.brakeCapacityPerDay)} USDw |`);
L.push(`| Bond each vendor needs so its merchants' honest defunds fit its weekly allowance | ${H.bondNeededForHonestDefunds.map(f).join(' / ')} |`);
L.push(`| Chain transactions per month: consumer / merchant | ${H.chainLoadPerMonth.consumer.tx.toFixed(1)} (${H.chainLoadPerMonth.consumer.KB.toFixed(0)} KB) / ${H.chainLoadPerMonth.merchant.tx.toFixed(1)} (${H.chainLoadPerMonth.merchant.KB.toFixed(0)} KB) |`);
L.push(`| Whole economy per day | ${f(H.chainLoadPerMonth.allUsersTxPerDay)} transactions, ${H.chainLoadPerMonth.allUsersMBPerDay.toFixed(1)} MB |`);
L.push('');
L.push('### 8.2 A stealthy broken chip (pays only its owner\'s fence chips; found by the solvency monitor, 95% of balances reporting)');
L.push('');
L.push('| Fences | Response | Detected on day | Lost: goods / swaps / defunds | Still in fences | Total shortfall | Haircut if shared | Attacker profit (break cost 50,000) |');
L.push('|---|---|---|---|---|---|---|---|');
for (const r of R.stealthy) L.push(`| ${r.scenario.fences} | ${resp(r.scenario)} | ${r.detectedOnDay ?? 'never'} | ${f(r.byExit.goods)} / ${f(r.byExit.swaps)} / ${f(r.byExit.defunds)} | ${f(r.fenceStockAtEnd)} | **${f(r.shortfall)}** | ${pct(r.haircutPct)} | ${f(r.attackerProfit)} |`);
L.push('');
L.push('**How much of the economy must report its balances** (100 fences, freshness 7 days):');
L.push('');
L.push('| Balances reporting | Detected on day | Shortfall | Haircut |');
L.push('|---|---|---|---|');
for (const r of R.coverage) L.push(`| ${(r.scenario.coverage * 100).toFixed(0)}% | ${r.detectedOnDay} | ${f(r.shortfall)} | ${pct(r.haircutPct)} |`);
L.push('');
L.push('### 8.3 Other incidents');
L.push('');
L.push('| Incident | Response | Detected on day | Shortfall | Vendor bond used | Haircut on everyone |');
L.push('|---|---|---|---|---|---|');
const row = (r) => L.push(`| ${r.scenario.kind} | ${resp(r.scenario)} | ${r.detectedOnDay ?? 'n/a'} | ${f(r.shortfall)} | ${f(r.coveredByBond)} | ${pct(r.haircutPct)} |`);
for (const r of R.sloppy) row(r);
for (const r of R.voucherKey) row(r);
for (const r of R.family) row(r);
L.push('');
L.push(`**Odometer** (a lifetime cap on what one chip identity may pay out, enforced by receiving chips): a broken chip that pays honest people directly can take at most the cap (${R.odometer.map((o) => f(o.direct)).join(' / ')} for caps of ${R.odometer.map((o) => f(o.odometer)).join(' / ')}). It does **not** bound a chip that pays only fences, because each fence is a separate genuine identity and the broken chip can misreport its odometer to fences whose owners never publish receipts.`);
L.push('');
L.push('### 8.4 Vendor bond needed to cover one broken chip (50 fences)');
L.push('');
L.push('| Response | Detected on day 1 | day 3 | day 7 | day 14 | day 30 |');
L.push('|---|---|---|---|---|---|');
for (const r of ['fresh', 'freeze']) {
  const rs = R.bondSizing.filter((x) => x.response === r);
  L.push(`| ${r === 'fresh' ? 'freshness, 7 days' : 'emergency freeze'} | ${rs.map((x) => f(x.shortfall)).join(' | ')} |`);
}
L.push('');
L.push('### 8.5 Who bears a loss the bonds do not cover (broken family, freshness 7 days)');
L.push('');
const lr = R.lossRules;
L.push('| Rule | Result |');
L.push('|---|---|');
L.push(`| Shared vault, pro-rata haircut | every holder loses ${lr.spreadFences.sharedProRataPctByVendor[0]}% |`);
L.push(`| Shared vault, last out loses | the vault pays merchants (who defund daily) in full; the people still holding balances when it runs dry, mostly consumers, lose ${lr.spreadFences.sharedLastOutPctForConsumersByVendor[0]}% |`);
L.push(`| One vault per vendor, no settlement | fails on **honest** traffic alone: the merchant-heavy vendors' vaults run dry after ${lr.spreadFences.perVendorVaultsNoSettlement.daysUntilHonestDefundsFail.filter((x) => x !== null).join(' and ')} days (weekly net flows ${lr.spreadFences.perVendorVaultsNoSettlement.netWeeklyFlow.map(f).join(' / ')}) |`);
L.push(`| One vault per vendor, settled by the last payer's vendor | the loss lands where the fences are, not on the broken vendor: fences spread over all vendors: ${lr.spreadFences.perVendorVaultsLastHopSettlement.lossPctByVendor.join('% / ')}% by vendor, broken vendor ${lr.spreadFences.perVendorVaultsLastHopSettlement.brokenVendorBearsPct}%; fences all at one honest vendor: that vendor's holders lose ${Math.max(...lr.fencesAtOneHonestVendor.perVendorVaultsLastHopSettlement.lossPctByVendor)}%, the broken vendor 0% |`);
L.push('');
const lc = R.lostChips;
L.push('### 8.6 Lost and stolen chips');
L.push('');
L.push(`At ${f(lc.lostPerYear)} lost chips a year (3% of chips) with an average balance of ${f(lc.ownerLossPerChip)}: owners lose ${f(lc.ownerLossPerYear)} a year in total (the whole balance, like cash); a finder without the PIN can spend at most ${f(lc.finderCanSpendPerChip)} per chip (${f(lc.finderGainPerYear)} a year). The system itself loses nothing: the rest of a lost balance stays in the vault as unclaimed backing.`);
L.push('<!-- BALANCE-SIM:END -->');
const md = L.join('\n');
writeFileSync(join(HERE, 'results', 'summary.md'), md + '\n');
let doc = readFileSync(DOC, 'utf8');
const a = doc.indexOf('<!-- BALANCE-SIM:BEGIN'), b = doc.indexOf('<!-- BALANCE-SIM:END -->');
if (a >= 0 && b > a) { doc = doc.slice(0, a) + md + doc.slice(b + '<!-- BALANCE-SIM:END -->'.length); writeFileSync(DOC, doc); console.log('doc tables replaced'); }
else console.log('markers not found; wrote results/summary.md only');
