// Builds the section 11 tables of docs/payment-account-design.md from sim/results/*.json and replaces the
// block between the SIM-RESULTS markers (or the placeholder on first run).
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const R = (f) => JSON.parse(readFileSync(join(HERE, 'results', f), 'utf8'));
const base = R('baseline.json');
const sweep = R('sweep-split-bond.json');
const vendor = R('vendor-topup.json');
const intensity = R('intensity.json');
const limits = R('limits.json');
const be = R('break-even.json');
const fmt = (x) => (typeof x === 'number' ? (Math.abs(x) >= 100 ? Math.round(x).toLocaleString('en-US') : String(Math.round(x * 100) / 100)) : String(x));
const pct = (x) => Math.round(x * 100) + '%';

const P = base.params;
const out = [];
out.push('<!-- SIM-RESULTS:BEGIN (generated by sim/summarize.mjs) -->');
out.push('### 11.2 Simulation set-up (ASSUMED model)', '');
out.push(`${P.users.toLocaleString('en-US')} devices for ${P.days} days, hourly steps: ${pct(P.merchantShare)} merchants (online ${pct(P.pOnlineHour.merchant)} of hours), ` +
  `${pct(P.rarelyOnlineShare)} of consumers rarely online (${pct(P.pOnlineHour.rarely)} of hours), the rest ${pct(P.pOnlineHour.regular)}; ${pct(P.chipShare)} chip tier. ` +
  `Each consumer makes ${P.paymentsPerDay} payments a day (${pct(P.merchantPaymentShare)} to merchants) with notes of ${P.denominations.join('/')} USDw loaded ${P.loadAmount} at a time. ` +
  `Merchants give change from their takings and cash the rest. Receivers apply the section 10 rules (hop caps, 72-hour freshness, unseen-origin refusal, limits, online look-up). ` +
  `${pct(P.cheaterShare)} of devices are ForgedCards: each loads notes, waits ${P.cheaterWaitHours} hours so receivers have seen its anchors, then for ${P.cheaterActiveHours} hours pays copies of the same notes ` +
  `(${P.cheaterPaymentsPerHour} attempts an hour) to receivers who are offline. The **aggressive** cheater then cashes its own copies first (so every receiver loses) and registers the ` +
  `profit-maximising number of fake claims; the **naive** cheater does neither. Losers claim when they next sync inside a ${P.claimWindowHours / 24}-day window.`, '');

out.push('### 11.3 Baseline (bond 250, victims\' share 50%, no claim fee, vendor top-up paid to claimants)', '');
out.push('| Measure | Value |', '|---|---|');
out.push(`| Honest payments accepted | ${pct(base.honest.acceptRate)} of ${fmt(base.honest.payments)} |`);
const refs = Object.entries(base.honest.refusals).sort((a, b) => b[1] - a[1]).map(([k, v]) => `${k} ${fmt(v)}`).join(', ');
out.push(`| Refusals | ${refs} |`);
out.push(`| Fraudulent value accepted | ${fmt(base.fraud.acceptedValue)} USDw (${base.cheaters.length} cheaters, ${fmt(base.fraud.acceptedValue / base.cheaters.length)} each) |`);
out.push(`| Honest losses / compensated | ${fmt(base.fraud.honestLoss)} / ${fmt(base.fraud.compensated)} (**coverage ${pct(base.fraud.coverage)}**) |`);
out.push(`| Burned from bonds | ${fmt(base.fraud.burned)} |`);
out.push(`| Mean cheater profit (phone keys; chips before the break cost) | ${fmt(avg(base.cheaters.filter((c) => c.tier === 'phone').map((c) => c.profit)))} ; ${fmt(avg(base.cheaters.filter((c) => c.tier === 'chip').map((c) => c.profitExBreakCost)))} |`);
out.push(`| Chain transactions per user per day | all ${base.chain.txnsPerUserPerDay}; merchants ${base.byGroup.merchants.txnsPerUserPerDay}; regular ${base.byGroup.regular.txnsPerUserPerDay}; rarely online ${base.byGroup.rarelyOnline.txnsPerUserPerDay} |`);
out.push(`| Losses by group (loss / compensated) | merchants ${fmt(base.byGroup.merchants.loss)} / ${fmt(base.byGroup.merchants.compensated)}; regular ${fmt(base.byGroup.regular.loss)} / ${fmt(base.byGroup.regular.compensated)}; rarely online ${fmt(base.byGroup.rarelyOnline.loss)} / ${fmt(base.byGroup.rarelyOnline.compensated)} |`, '');

out.push('### 11.4 Slash split, claim fee and bond size (mean of 2 seeds, 2,000 devices, vendor money burned)', '');
out.push('| Cheater | Claim fee | Victims\' share s | Bond | Phone cheater profit | Chip cheater profit before break cost | Honest loss | Compensated | Coverage | Burned |', '|---|---|---|---|---|---|---|---|---|---|');
for (const x of sweep) out.push(`| ${x.strategy} | ${pct(x.claimFee)} | ${pct(x.victimShare)} | ${x.bond} | ${fmt(x.meanProfitPhoneCheater)} | ${fmt(x.meanProfitChipCheaterExBreak)} | ${fmt(x.honestLoss)} | ${fmt(x.compensated)} | ${pct(x.coverage)} | ${fmt(x.burned)} |`);
out.push('');

out.push('### 11.5 Vendor top-up paid to claimants versus burned (chip-tier cheaters only)', '');
out.push('| Vendor money to claimants | Claim fee | Chip cheater profit before break cost | Taken back by fake claims (mean) | Victims\' coverage |', '|---|---|---|---|---|');
for (const x of vendor) out.push(`| ${x.vendorTopUpToVictims ? 'yes' : 'no (burned)'} | ${pct(x.claimFee)} | ${fmt(x.chipCheaterProfitExBreak)} | ${fmt(x.puppetRecoveredMean)} | ${pct(x.coverage)} |`);
out.push('');

out.push('### 11.6 How far one cheating identity reaches', '');
out.push('| Attempts per hour | Targets only offline receivers | Goods obtained per cheater (USDw) | Phone cheater profit |', '|---|---|---|---|');
for (const x of intensity) out.push(`| ${x.attemptsPerHour} | ${x.targetsOffline ? 'yes' : 'no'} | ${fmt(x.goodsPerCheater)} | ${fmt(x.profitPhoneMean)} |`);
out.push('');

out.push('### 11.7 Phone-only offline limit and rarely-online users', '');
out.push('| Phone limit per payment | Rarely-online share | Honest acceptance | Goods per cheater | Tx/user/day (all, merchants, regular) |', '|---|---|---|---|---|');
for (const x of limits) out.push(`| ${x.phonePerPayment} | ${pct(x.rarelyOnlineShare)} | ${pct(x.acceptRate)} | ${fmt(x.goodsPerCheater)} | ${x.txnsPerUserPerDay}, ${x.byGroup.merchants.txnsPerUserPerDay}, ${x.byGroup.regular.txnsPerUserPerDay} |`);
out.push('');

const rec = R('recommended.json');
out.push('### 11.8 The recommended configuration (phone 20 per payment with bond 500; chip bond 1,000; 25 % to victims; 10 % claim fee; vendor money burned)', '');
out.push('| Chip limit per payment | Cheater attempts per hour | Chip break cost | Phone cheater profit | Chip cheater profit | Victims\' coverage | Honest acceptance | Tx/user/day (all, merchants, regular) |', '|---|---|---|---|---|---|---|---|');
for (const x of rec) out.push(`| ${x.chipLimit} | ${x.attemptsPerHour} | ${fmt(x.chipBreakCost)} | ${fmt(x.phoneCheaterProfit)} | ${fmt(x.chipCheaterProfit)} | ${pct(x.coverage)} | ${pct(x.honestAccept)} | ${x.txPerUserDay}, ${x.merchantsTx}, ${x.regularTx} |`);
out.push('');

out.push('### 11.9 Break-even device bond from the formula (bond needed so that fraud does not pay)', '');
out.push('| Victims reached N | Accepted each L | s | Worst case (cheater claws back s·B) | Naive cheater | Chip, break cost 3,000, worst case |', '|---|---|---|---|---|---|');
for (const x of be) out.push(`| ${x.N} | ${x.L} | ${pct(x.s)} | ${fmt(x.bondWorstCase)} | ${fmt(x.bondNaive)} | ${fmt(x.chipBondWorstCase_K3000)} |`);
out.push('');
out.push('<!-- SIM-RESULTS:END -->');
function avg(xs) { return xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0; }

const docPath = join(HERE, '..', 'docs', 'payment-account-design.md');
let doc = readFileSync(docPath, 'utf8');
const block = out.join('\n');
if (doc.includes('<!-- SIM-RESULTS:BEGIN')) doc = doc.replace(/<!-- SIM-RESULTS:BEGIN[\s\S]*?<!-- SIM-RESULTS:END -->/, block);
else doc = doc.replace('SIM_RESULTS_PLACEHOLDER', block);
writeFileSync(docPath, doc);
console.log(block);
